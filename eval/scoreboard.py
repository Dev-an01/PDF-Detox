"""Score a milestone's predictions and append one row per score set to docs/scores.md.

    python eval/scoreboard.py NAME GOLD_PRED_DIR PB_PRED_DIR [--note "text"]

Runs evaluate.py on gold (all / sample / text-layer / ocr / ja) and ParseBench dev + test
(--no-teds), then appends to docs/scores.md (human) and docs/scores.jsonl (machine). Re-running a NAME
replaces its rows.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "eval"))
import evaluate as ev  # noqa: E402

KEYS = [("table_f1", "F1"), ("teds_struct", "TEDS-s"), ("cell_exact_acc", "cell"), ("numeric_exact_acc", "num"),
        ("numeric_errors_unflagged", "UNFLAG"), ("review_pct", "review%"), ("column_shifts", "shifts"),
        ("rows_missing", "miss"), ("rows_extra", "extra"), ("numbers", "nums"), ("numbers_flagged", "flagged"),
        ("numeric_errors", "wrong"), ("numeric_errors_split_only", "wrong_split"),
        ("numeric_errors_unflagged_split_only", "unflag_split")]


def score(name, gold_pred, pb_pred, note=""):
    g = ev.run(ROOT / "gold" / "json", gold_pred)
    sets = {"gold all": g["summary"], "sample": g["by_tag"]["real"], "gold text": g["by_tag"]["text_layer"],
            "gold ocr": g["by_tag"]["ocr"], "gold ja": g["by_tag"]["ja"]}
    for part in ("dev", "test"):
        sets[f"PB {part}"] = ev.run(ROOT / "eval" / f"parsebench_{part}", pb_pred, with_teds=False)["summary"]
    rows = [{"milestone": name, "set": k, "note": note, **{key: v.get(key) for key, _ in KEYS}} for k, v in sets.items()]
    jl = ROOT / "docs" / "scores.jsonl"
    old = [json.loads(l) for l in jl.read_text().splitlines()] if jl.exists() else []
    old = [r for r in old if r["milestone"] != name] + rows
    jl.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in old))
    md = ["# Scores per milestone", "", "Generated by `eval/scoreboard.py` (eval v2, gold v2). `UNFLAG` = wrong numbers not "
          "flagged for review (target 0). `review%` = share of numeric cells flagged (once m4 exists). "
          "ParseBench numeric exact compares printed text.", "",
          "| milestone | set | " + " | ".join(h for _, h in KEYS) + " | note |",
          "|" + "---|" * (len(KEYS) + 3)]
    for r in old:
        md.append(f"| {r['milestone']} | {r['set']} | " + " | ".join("" if r.get(k) is None else str(r[k]) for k, _ in KEYS)
                  + f" | {r.get('note', '')} |")
    (ROOT / "docs" / "scores.md").write_text("\n".join(md) + "\n")
    import dashboard  # eval/dashboard.py: scores.jsonl -> scores.html, kept current after every milestone
    dashboard.main()
    return sets


if __name__ == "__main__":
    note = sys.argv[sys.argv.index("--note") + 1] if "--note" in sys.argv else ""
    sets = score(sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3]), note)
    print(f"{'set':10s}" + "".join(f"{h:>9s}" for _, h in KEYS))
    for k, v in sets.items():
        print(f"{k:10s}" + "".join(f"{str(v.get(key)):>9s}" for key, _ in KEYS))
